// Runs the test suite with coverage and enforces a minimum line coverage.
//
// Usage: dart run tool/coverage.dart [--min 80]
//
// Why a script instead of `flutter test --coverage` alone:
//  * Flutter only reports files that some test imports, so untested files would
//    silently be left out and inflate the number. This script generates a
//    temporary helper test that imports every file under lib/.
//  * It excludes files that are not worth measuring (entry points, generated
//    code, or files marked with `// coverage:ignore-file`).
import 'dart:io';

const _defaultMin = 80.0;
const _helperPath = 'test/_coverage_helper_test.dart';
const _lcovPath = 'coverage/lcov.info';

const _excludedFiles = {'lib/main.dart', 'lib/app.dart'};
const _generatedSuffixes = ['.g.dart', '.freezed.dart', '.gr.dart'];

Future<void> main(List<String> args) async {
  final min = _parseMin(args);
  final helper = File(_helperPath);

  int exitCodeFromTests;
  try {
    helper.writeAsStringSync(_helperSource());
    exitCodeFromTests = await _runFlutterTest();
  } finally {
    if (helper.existsSync()) helper.deleteSync();
  }

  if (exitCodeFromTests != 0) {
    stderr.writeln('Tests failed; skipping coverage check.');
    exit(exitCodeFromTests);
  }

  final lcov = File(_lcovPath);
  if (!lcov.existsSync()) {
    stderr.writeln('No $_lcovPath found.');
    exit(1);
  }

  final records = _parseLcov(lcov.readAsLinesSync());
  var found = 0;
  var hit = 0;
  final rows = <({String path, int found, int hit})>[];

  records.forEach((path, r) {
    if (_isExcluded(path) || r.found == 0) return;
    found += r.found;
    hit += r.hit;
    rows.add((path: path, found: r.found, hit: r.hit));
  });

  rows.sort((a, b) => (a.hit / a.found).compareTo(b.hit / b.found));
  stdout.writeln('\nCoverage by file (lowest first):');
  for (final row in rows) {
    final pct = (row.hit / row.found * 100).toStringAsFixed(1).padLeft(5);
    stdout.writeln('  $pct%  ${row.path} (${row.hit}/${row.found})');
  }

  final total = found == 0 ? 100.0 : hit / found * 100;
  stdout.writeln(
    '\nTotal: ${total.toStringAsFixed(1)}% ($hit/$found lines), '
    'required: ${min.toStringAsFixed(0)}%',
  );

  if (total < min) {
    stderr.writeln('Coverage is below the required minimum.');
    exit(1);
  }
}

double _parseMin(List<String> args) {
  final i = args.indexOf('--min');
  if (i == -1 || i + 1 >= args.length) return _defaultMin;
  return double.tryParse(args[i + 1]) ?? _defaultMin;
}

String _packageName() {
  final line = File('pubspec.yaml')
      .readAsLinesSync()
      .firstWhere((l) => l.startsWith('name:'));
  return line.substring('name:'.length).trim();
}

String _helperSource() {
  final package = _packageName();
  final files =
      Directory('lib')
          .listSync(recursive: true)
          .whereType<File>()
          .where((f) => f.path.endsWith('.dart'))
          .where(
            (f) =>
                !File(f.path)
                    .readAsStringSync()
                    .contains(RegExp(r'^part of ', multiLine: true)),
          )
          .map((f) => f.path.replaceAll('\\', '/'))
          .toList()
        ..sort();

  final b = StringBuffer()
    ..writeln('// Generated by tool/coverage.dart. Do not commit.')
    ..writeln('// ignore_for_file: unused_import, directives_ordering')
    ..writeln("import 'package:flutter_test/flutter_test.dart';");
  for (var i = 0; i < files.length; i++) {
    final rel = files[i].substring('lib/'.length);
    b.writeln("import 'package:$package/$rel' as i$i;");
  }
  b
    ..writeln('\nvoid main() {')
    ..writeln("  test('loads every library file for coverage', () {});")
    ..writeln('}');
  return b.toString();
}

Future<int> _runFlutterTest() async {
  final process = await Process.start(
    'flutter',
    ['test', '--coverage'],
    mode: ProcessStartMode.inheritStdio,
    runInShell: Platform.isWindows,
  );
  return process.exitCode;
}

Map<String, ({int found, int hit})> _parseLcov(List<String> lines) {
  final records = <String, ({int found, int hit})>{};
  String? current;
  var lf = 0;
  var lh = 0;
  for (final line in lines) {
    if (line.startsWith('SF:')) {
      current = _normalize(line.substring(3));
      lf = 0;
      lh = 0;
    } else if (line.startsWith('LF:')) {
      lf = int.parse(line.substring(3));
    } else if (line.startsWith('LH:')) {
      lh = int.parse(line.substring(3));
    } else if (line == 'end_of_record' && current != null) {
      records[current] = (found: lf, hit: lh);
      current = null;
    }
  }
  return records;
}

String _normalize(String path) {
  var p = path.replaceAll('\\', '/');
  if (p.startsWith('./')) p = p.substring(2);
  final i = p.indexOf('lib/');
  return i == -1 ? p : p.substring(i);
}

bool _isExcluded(String path) {
  if (_excludedFiles.contains(path)) return true;
  if (_generatedSuffixes.any(path.endsWith)) return true;
  final file = File(path);
  return file.existsSync() &&
      file.readAsStringSync().contains('coverage:ignore-file');
}
